import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { runInNewContext } from 'node:vm';
import { join, dirname, resolve } from 'node:path';
import { mkdir, readFile, realpath } from 'node:fs/promises';
import { atomic, json } from '../embedded-skill/lib/common.mjs';
import { command } from '../embedded-skill/lib/process.mjs';

const installDir = process.env.DSH_INSTALL_DIR || resolve(dirname(await realpath((await command('which', ['dsh'])).stdout.trim())), '..');
const fromDsh = createRequire(join(installDir, 'package.json'));
const modules = name => import(pathToFileURL(fromDsh.resolve(`@deepseek-ai/${name}`)).href);
const { Context } = await modules('cordis'), { default: SkillRegistry } = await modules('dsh-skill');
const { parseMarketIndex } = await modules('dsh-plugin-market-index');
const { readProfileManifest, getDshRuntimeVersion, evaluatePluginCompatibility, bundlePatchPaths, loadOverlayPatches, composeEntries } = await modules('dsh-app-boot');
const bundleDir = process.argv[2] ? resolve(process.argv[2]) : fileURLToPath(new URL('../', import.meta.url));
const manifest = readProfileManifest('dsh', bundleDir);
assert.equal(manifest.name, 'dsh-mek-media-workflow');
assert.ok(manifest.dsh?.bundle, '仓库根或解包目录必须声明 DSH 组合包');
assert.equal(evaluatePluginCompatibility(manifest), undefined);
const patches = bundlePatchPaths(bundleDir, manifest.dsh.bundle).flatMap(path => loadOverlayPatches('dsh', path));
assert.deepEqual(composeEntries([patches]).map(({ id, name }) => ({ id, name })), [{ id: 'media-workflow', name: manifest.name }]);
assert.equal(manifest.dsh?.client?.platform, 'web');
const fromBundle = createRequire(join(bundleDir, 'package.json'));
const { apply } = await import(pathToFileURL(fromBundle.resolve(manifest.name)).href);
let client;
runInNewContext(await readFile(fromBundle.resolve(`${manifest.name}/client`), 'utf8'), { window: { __ModuleLoader__: { load(value) { client = value; } } } });
assert.equal(client?.id, manifest.name);
assert.equal(typeof client?.factory, 'function');
const root = resolve(`artifacts/host-smoke-${Date.now()}`); await mkdir(root, { recursive: true });
const ctx = new Context(), routes = new Map();
ctx.provide('connection', { fetch: { register(route) { assert.equal(routes.has(route.path), false); routes.set(route.path, route); return () => routes.delete(route.path); } } });
ctx.plugin(SkillRegistry);
const configuration = { root, locationFile: join(root, 'host-location.json') };
const definition = { name: 'media-workflow-host-smoke', inject: ['connection', 'skills'], apply };
const plugin = ctx.plugin(definition, configuration);
try {
  for (let n = 0; n < 100 && routes.size !== 9; n++) await new Promise(r => setTimeout(r, 20));
  assert.equal(routes.size, 9); const skills = await ctx.skills.list(); assert.ok(skills.some(s => s.name === 'media-workflow'));
  const skill = await ctx.skills.get('media-workflow'); assert.ok(skill.content.includes('十步')); assert.ok(skill.resourceBase.path.endsWith('/embedded-skill/'));
  const market = parseMarketIndex(await json(resolve('market-index.json')), 'https://example.invalid/media-workflow/market-index.json'); assert.equal(market.plugins.length, 0);
  const route = routes.get('/api/dsh-media-workflow'); const response = await route.fetch(new Request('http://localhost/api/dsh-media-workflow', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ type: 'client-request', rpcId: 'smoke', method: 'dsh-media-workflow', payload: { method: 'tasks.list', payload: {} } }) }));
  assert.equal((await response.json()).result.value.total, 0);
  const sample = await routes.get('/api/dsh-media-workflow/sample').fetch(new Request(`http://localhost/api/dsh-media-workflow/sample?name=${encodeURIComponent('冰糖')}`));
  assert.equal(sample.status, 200); assert.equal(sample.headers.get('content-type'), 'audio/mpeg'); assert.ok((await sample.arrayBuffer()).byteLength > 0);
  for (let n = 0; n < 200 && !await json(join(root, 'dsh.patch'), null); n++) await new Promise(r => setTimeout(r, 50));
  assert.equal((await json(join(root, 'dsh.patch'))).kind, 'media-workflow-diagnostics');
  const nextRoot = join(root, '内容创作');
  for (let n = 0; n < 30; n++) {
    const changed = await route.fetch(new Request('http://localhost/api/dsh-media-workflow', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ type: 'client-request', rpcId: 'storage-smoke', method: 'dsh-media-workflow', payload: { method: 'storage.set', payload: { root: nextRoot, expectedRoot: root } } }) }));
    const body = await changed.json(); if (body.result.ok) break;
    if (body.result.error.code !== 'busy' || n === 29) throw new Error(body.result.error.message);
    await new Promise(r => setTimeout(r, 20));
  }
  assert.equal((await json(configuration.locationFile)).root, nextRoot);
  assert.ok((await ctx.skills.get('media-workflow')).content.includes(nextRoot));
  await plugin.dispose(); assert.equal(routes.size, 0); assert.equal((await ctx.skills.list()).some(s => s.name === 'media-workflow'), false);
  const reloaded = ctx.plugin(definition, configuration);
  for (let n = 0; n < 100 && routes.size !== 9; n++) await new Promise(r => setTimeout(r, 20));
  assert.equal(routes.size, 9); assert.ok((await ctx.skills.get('media-workflow')).content.includes(nextRoot));
  await reloaded.dispose(); assert.equal(routes.size, 0);
  const record = { passed: true, bundleDir, dshVersion: getDshRuntimeVersion(), checks: ['DSH manifest, compatibility and patch composition', 'host and web module exports', 'installed Cordis lifecycle', 'installed DSH skill registry provider list/get', 'real market-index parser', 'host RPC', 'startup doctor diagnostic snapshots', 'runtime directory switch and live skill root', 'directory retained across plugin recreation', 'provider and route disposal', 'voice sample route'], boundary: '真实 DSH 加载器、Cordis 与 skills 服务；connection 为隔离路由夹具，未安装插件或启动日常 DSH，未访问发布平台' }; await atomic(join(root, 'result.json'), record); console.log(JSON.stringify(record, null, 2));
} finally { await ctx.fiber.dispose(); }
