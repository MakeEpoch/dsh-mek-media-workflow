// Poll the store from Node: an async page predicate resolves immediately because the returned Promise is truthy.
async function waitForStatus(id, status, timeout = 30000) {
  const started = Date.now();
  while (Date.now() - started < timeout) { if ((await service.store.read(id)).state.status === status) return; await new Promise(r => setTimeout(r, 100)); }
  throw new Error(`任务 ${id} 未在 ${timeout}ms 内进入 ${status}，当前为 ${(await service.store.read(id)).state.status}`);
}
